// Writes dist/<site>/static (your own domain) and dist/<site>/apps-script (for clasp push).
import fs from "node:fs";
import path from "node:path";
import { sitePaths, loadSite, loadPages, loadAbout, loadHubIntro, execUrl, RESERVED } from "./project.js";
import { renderHome, renderHub, renderIndex, renderGuides, renderAbout, renderSitemap, renderPage } from "./render.js";

// Apps Script file names: letters, numbers and underscores.
const fileName = (key) => `p_${(key || "home").replace(/[^a-z0-9]+/gi, "_")}`;

// Every page of the site as { key, title, html(ctx) }. key "" is the home page.
export function sitePagesFor(siteName, { includeDrafts = false, preview = false } = {}) {
  const site = loadSite(siteName);
  // Preview renders Apps Script links against a fake deployment so the dev server can rewrite them.
  if (preview) site.appsScript = { ...site.appsScript, deploymentId: "PREVIEW" };
  const loaded = loadPages(siteName);
  const broken = loaded.filter((p) => p.error);
  if (broken.length) throw new Error(`Fix these pages first (run "npm run validate"):\n${broken.map((b) => `- pages/${b.slug}: ${b.error.split("\n")[0]}`).join("\n")}`);
  const hubSlugs = new Set(site.hubs.map((h) => h.slug));
  const clash = loaded.filter((p) => RESERVED.has(p.slug) || hubSlugs.has(p.slug));
  if (clash.length) throw new Error(`These slugs are reserved for the site shell or a hub: ${clash.map((p) => p.slug).join(", ")}`);
  const badHub = loaded.filter((p) => !p.error && p.meta.hub && !hubSlugs.has(p.meta.hub));
  if (badHub.length) throw new Error(`These pages point to a hub that is not in site.json: ${badHub.map((p) => `${p.slug} -> ${p.meta.hub}`).join(", ")}`);
  const pages = loaded.filter((p) => includeDrafts || p.meta.status === "approved")
    .sort((a, b) => b.meta.updated.localeCompare(a.meta.updated));
  const about = loadAbout(siteName);
  const ctxFor = (target, slug) => ({ site, target, pages, slug });
  const pageEntry = (p, key = p.slug) => ({ key, title: p.meta.title, updated: p.meta.updated, html: (t) => renderPage(ctxFor(t, key), p) });
  if (site.mode === "single") {
    // One page is the whole site. It answers at the bare /exec URL.
    if (pages.length !== 1) throw new Error(`A "single" site needs exactly 1 approved page; "${siteName}" has ${pages.length}.`);
    return { site, pages, entries: [pageEntry(pages[0], "")], skipped: loaded.length - pages.length };
  }
  if (site.mode === "hub") {
    // A home page that links to every page. Pages have a logo + CTA header and a footer that links to every other page.
    const entries = [{ key: "", title: site.home.title, html: (t) => renderIndex(ctxFor(t, "")) }, ...pages.map((p) => pageEntry(p))];
    return { site, pages, entries, skipped: loaded.length - pages.length };
  }
  const entries = [
    { key: "", title: site.home.title, html: (t) => renderHome(ctxFor(t, "")) },
    { key: "guides", title: `All guides | ${site.name}`, html: (t) => renderGuides(ctxFor(t, "guides")) },
    { key: "about", title: `About | ${site.name}`, html: (t) => renderAbout(ctxFor(t, "about"), about) },
    { key: "sitemap", title: `Sitemap | ${site.name}`, html: (t) => renderSitemap(ctxFor(t, "sitemap")) },
    ...site.hubs.map((h) => ({ key: h.slug, title: `${h.title} | ${site.name}`, html: (t) => renderHub(ctxFor(t, h.slug), h, loadHubIntro(siteName, h.slug)) })),
    ...pages.map((p) => ({ key: p.slug, title: p.meta.title, updated: p.meta.updated, html: (t) => renderPage(ctxFor(t, p.slug), p) })),
  ];
  return { site, pages, entries, skipped: loaded.length - pages.length };
}

// Absolute URL of a page for a target. Apps Script uses the /exec URL; static uses static.baseUrl.
function absFor(site, target, key) {
  if (target === "apps-script") {
    const base = execUrl(site);
    if (!base) return "";
    if (!key) return base;
    return site.appsScript.urlStyle === "path" ? `${base}/${key}` : `${base}?page=${encodeURIComponent(key)}`;
  }
  const base = site.static.baseUrl.replace(/\/+$/, "");
  return base ? `${base}/${key ? key + "/" : ""}` : "";
}

export function sitemapXml(site, entries, target) {
  const xmlEsc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
  const rows = entries.map((e) => ({ loc: absFor(site, target, e.key), updated: e.updated })).filter((r) => r.loc);
  if (!rows.length) return "";
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${rows.map((r) => `  <url><loc>${xmlEsc(r.loc)}</loc>${r.updated ? `<lastmod>${r.updated}</lastmod>` : ""}</url>`).join("\n")}\n</urlset>\n`;
}

function codeJs(entries, sitemap) {
  const map = Object.fromEntries(entries.map((e) => [e.key, { file: fileName(e.key), title: e.title }]));
  return `// Generated by apps-script-launch-kit. Do not edit by hand: change the pages and run "npm run build".
var PAGES = ${JSON.stringify(map, null, 2)};

// XML sitemap, served at ?page=sitemap.xml. Apps Script answers text output with a one-time
// redirect to script.googleusercontent.com; link the stable /exec URL, never the redirect target.
var SITEMAP = ${JSON.stringify(sitemap)};

// Serves one page per key: ?page=<slug> or /exec/<slug>. Unknown keys get the home page.
// Every visitor and every crawler gets the same HTML. No redirects, no user-agent checks.
function doGet(e) {
  var key = "";
  if (e && e.parameter && e.parameter.page) key = String(e.parameter.page);
  else if (e && e.pathInfo) key = String(e.pathInfo).replace(/\\/+$/, "");
  if ((key === "sitemap.xml" || key === "sitemap-xml") && SITEMAP) {
    return ContentService.createTextOutput(SITEMAP).setMimeType(ContentService.MimeType.XML);
  }
  var page = PAGES[key] || PAGES[""];
  return HtmlService.createHtmlOutputFromFile(page.file)
    .setTitle(page.title)
    .addMetaTag("viewport", "width=device-width, initial-scale=1");
}
`;
}

const manifest = (site) => ({
  timeZone: site.appsScript.timeZone,
  exceptionLogging: "STACKDRIVER",
  runtimeVersion: "V8",
  webapp: { executeAs: "USER_DEPLOYING", access: "ANYONE_ANONYMOUS" },
});

function clean(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
}

export function build(siteName, opts = {}) {
  const { site, pages, entries, skipped } = sitePagesFor(siteName, opts);
  const { dist } = sitePaths(siteName);

  // Static target: /index.html and /<key>/index.html
  const staticDir = path.join(dist, "static");
  clean(staticDir);
  for (const e of entries) {
    const dir = path.join(staticDir, e.key);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "index.html"), e.html("static"));
  }
  const base = site.static.baseUrl.replace(/\/+$/, "");
  if (base && site.sitemap !== false) {
    const urls = entries.map((e) => `  <url><loc>${base}/${e.key ? e.key + "/" : ""}</loc>${e.updated ? `<lastmod>${e.updated}</lastmod>` : ""}</url>`);
    fs.writeFileSync(path.join(staticDir, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`);
    fs.writeFileSync(path.join(staticDir, "robots.txt"), `User-agent: *\nAllow: /\nSitemap: ${base}/sitemap.xml\n`);
  }

  // Apps Script target
  const asDir = path.join(dist, "apps-script");
  clean(asDir);
  fs.writeFileSync(path.join(asDir, "Code.js"), codeJs(entries, site.sitemap === false ? "" : sitemapXml(site, entries, "apps-script")));
  fs.writeFileSync(path.join(asDir, "appsscript.json"), JSON.stringify(manifest(site), null, 2) + "\n");
  for (const e of entries) fs.writeFileSync(path.join(asDir, `${fileName(e.key)}.html`), e.html("apps-script"));
  // Push only the manifest, server code and HTML pages.
  fs.writeFileSync(path.join(asDir, ".claspignore"), "**/**\n!appsscript.json\n!**/*.js\n!**/*.html\n");
  if (site.appsScript.scriptId) {
    fs.writeFileSync(path.join(asDir, ".clasp.json"), JSON.stringify({ scriptId: site.appsScript.scriptId, srcDir: "." }, null, 2) + "\n");
  }
  return { site, pages, skipped, staticDir, asDir, execUrl: execUrl(site) };
}
